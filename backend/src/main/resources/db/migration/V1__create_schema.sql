CREATE TABLE monitors (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(100)  NOT NULL,
    url                  VARCHAR(2048) NOT NULL,
    interval_seconds     INTEGER       NOT NULL,
    expected_status      INTEGER       NOT NULL,
    latency_threshold_ms INTEGER       NOT NULL,
    failure_threshold    INTEGER       NOT NULL,
    paused               BOOLEAN       NOT NULL DEFAULT FALSE,
    status               VARCHAR(20)   NOT NULL,
    consecutive_failures INTEGER       NOT NULL DEFAULT 0,
    last_checked_at      TIMESTAMP WITH TIME ZONE,
    last_latency_ms      BIGINT,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE check_results (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monitor_id    BIGINT       NOT NULL REFERENCES monitors (id) ON DELETE CASCADE,
    checked_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    outcome       VARCHAR(20)  NOT NULL,
    status_code   INTEGER,
    latency_ms    BIGINT       NOT NULL,
    error_message VARCHAR(500)
);

-- Dashboard queries read one monitor's recent checks; the retention job deletes by time.
CREATE INDEX idx_check_results_monitor_time ON check_results (monitor_id, checked_at);
CREATE INDEX idx_check_results_time ON check_results (checked_at);

CREATE TABLE incidents (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monitor_id  BIGINT       NOT NULL REFERENCES monitors (id) ON DELETE CASCADE,
    started_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at TIMESTAMP WITH TIME ZONE,
    cause       VARCHAR(500) NOT NULL
);

CREATE INDEX idx_incidents_monitor_open ON incidents (monitor_id, resolved_at);
CREATE INDEX idx_incidents_started ON incidents (started_at);
